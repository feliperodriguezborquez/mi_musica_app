def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, 'data.json')
    data = json.loads(io.open(path, encoding='utf-8', newline='').read())
    updated = 0
    for song in data:
        sid = song.get('id')
        if sid in PDF_LYRICS:
            song['letras'] = {
                'sincronizada': False,
                'lineas': [{'t': None, 'text': line} for line in PDF_LYRICS[sid]],
            }
            updated += 1
    text = json.dumps(data, indent=4, ensure_ascii=False).replace('\n', '\r\n')
    io.open(path, 'w', encoding='utf-8', newline='').write(text)
    print(f'Letras de PDF guardadas en data.json para {updated} canciones.')


if __name__ == '__main__':
    main()
